/* Lakitu's Cloud - Favorites tab (display + copy + user-tapped 'Message on Vinted' chat links; never contacts Vinted itself).
   Loaded by index.html (generated by /workspace/lakitu/update.py). Reads the public JSON feed
   written by /workspace/lakitu/favorites/publish.py, fetched fresh with a cache-busting query. */
(function(){
  var me=document.currentScript, FEED=(me&&me.getAttribute('data-feed'))||'favorites-8265eaa69a16.json';
  var css='.tabs{display:flex;gap:0;margin:0 0 14px;max-width:900px;border:1px solid #2dd4bf;border-radius:8px;overflow:hidden}'+
  '.tabs button{flex:1 1 0;padding:12px 8px;background:#1a1f22;color:#e6e6e6;border:0;font-size:16px;font-weight:600;cursor:pointer;min-height:44px}'+
  '.tabs button+button{border-left:1px solid #2dd4bf}.tabs button.on{background:#2dd4bf;color:#0f1214}'+
  '#fav{max-width:900px}#fav .fbar{display:flex;flex-wrap:wrap;gap:8px;align-items:center}'+
  '#fq{flex:1 1 220px;min-width:0;padding:10px;background:#1a1f22;border:1px solid #2dd4bf;color:#fff;border-radius:6px;font-size:16px;box-sizing:border-box}'+
  '#fav .tg{display:flex;align-items:center;gap:6px;font-size:15px;padding:8px 4px;cursor:pointer;user-select:none}#fav .tg input{width:20px;height:20px;accent-color:#2dd4bf}'+
  '#fav .fst{color:#999;font-size:13px;margin:10px 0}'+
  '.fg{background:#1a1f22;border:1px solid #233;border-radius:8px;padding:12px;margin:0 0 12px}'+
  '.fh{display:flex;flex-wrap:wrap;gap:4px 10px;align-items:baseline}.fh a{font-weight:600;font-size:16px;overflow-wrap:anywhere}'+
  '.fh .pr{color:#2dd4bf;font-weight:bold}.fh .ct{color:#999;font-size:13px}'+
  '.fr{border-top:1px solid #233;margin-top:10px;padding-top:10px}.fr .who{display:flex;flex-wrap:wrap;gap:4px 10px;align-items:baseline}'+
  '.fr .who a{font-weight:600;overflow-wrap:anywhere}.fr .tm{color:#999;font-size:13px}'+
  '.fr .who a.un.ok{background:#2dd4bf;color:#0f1214;border-radius:4px}.fr .who a.pf{font-weight:400;font-size:12px;color:#999;text-decoration:underline}'+
  '.fr .its{font-size:13px;color:#bbb;margin:4px 0 0;padding-left:18px}.fr .its li{margin:2px 0}'+
  '.fr .msg{display:flex;gap:8px;align-items:flex-start;margin-top:6px}.fr .msg div{flex:1 1 auto;min-width:0;background:#0f1214;border:1px solid #233;border-radius:6px;padding:8px;font-size:14px;line-height:1.4;overflow-wrap:anywhere}'+
  '.fr .cp{flex:0 0 auto;padding:10px 14px;min-height:40px;background:#1a1f22;border:1px solid #2dd4bf;color:#2dd4bf;border-radius:6px;font-size:14px;font-weight:600;cursor:pointer}'+
  '.fr .cp.ok{background:#2dd4bf;color:#0f1214}'+
  '.fr .msg .acts{flex:0 0 220px;display:flex;flex-direction:column;gap:6px;max-width:220px;min-width:0;background:none;border:0;border-radius:0;padding:0}'+
  '.fr .mv{display:block;box-sizing:border-box;padding:10px 14px;min-height:40px;background:#2dd4bf;border:1px solid #2dd4bf;color:#0f1214;border-radius:6px;font-size:14px;font-weight:600;text-decoration:none;text-align:center;cursor:pointer}'+
  '.fr .mv small{display:block;font-weight:400;font-size:12px;overflow:hidden;text-overflow:ellipsis;white-space:nowrap}'+
  '.fr .mv.ok{background:#0f1214;color:#2dd4bf}'+
  '#ftoast{position:fixed;left:50%;bottom:24px;transform:translateX(-50%);z-index:9999;background:#2dd4bf;color:#0f1214;padding:12px 18px;border-radius:8px;font-size:15px;font-weight:600;box-shadow:0 4px 16px rgba(0,0,0,.5);max-width:90vw;text-align:center;opacity:0;pointer-events:none;transition:opacity .2s}'+
  '#ftoast.on{opacity:1}#ftoast.bad{background:#f87171}'+
  '@media(max-width:700px){.tabs{max-width:100%}.fg{padding:10px}.fr .msg{flex-direction:column}.fr .cp{width:100%}.fr .msg .acts{flex:0 0 auto;width:100%;max-width:none;box-sizing:border-box}}';
  var st=document.createElement('style');st.textContent=css;document.head.appendChild(st);

  var inv=document.getElementById('inv'),fav=document.getElementById('fav');
  if(!inv||!fav)return;
  var tabs=document.createElement('div');tabs.className='tabs';tabs.setAttribute('role','tablist');
  tabs.innerHTML='<button type="button" data-v="inv" class="on" role="tab">Inventory</button><button type="button" data-v="fav" role="tab">\u2605 Favorites</button>';
  inv.parentNode.insertBefore(tabs,inv);
  fav.innerHTML='<div class="fbar"><input id="fq" type="search" placeholder="Search favorites by item or username..." autocomplete="off">'+
    '<label class="tg"><input type="checkbox" id="fp"> Group by person</label></div><div class="fst" id="fst">Loading favorites\u2026</div><div id="fl"></div>';
  var fq=document.getElementById('fq'),fp=document.getElementById('fp'),fst=document.getElementById('fst'),fl=document.getElementById('fl');
  var data=null,loading=false,updatedAt='';

  function show(v){
    var f=v==='fav';inv.hidden=f;fav.hidden=!f;
    [].forEach.call(tabs.children,function(b){var on=b.getAttribute('data-v')===v;b.className=on?'on':'';b.setAttribute('aria-selected',on)});
    if(f)load();
  }
  tabs.addEventListener('click',function(e){var b=e.target.closest('button');if(!b)return;var v=b.getAttribute('data-v');
    try{history.replaceState(null,'',v==='fav'?'#favorites':location.pathname+location.search)}catch(_){}show(v)});

  function load(){
    if(loading)return;loading=true;fst.textContent='Loading favorites\u2026';
    fetch(FEED+'?t='+Date.now(),{cache:'no-store'}).then(function(r){if(!r.ok)throw new Error('HTTP '+r.status);return r.json()})
    .then(function(d){data=(d&&d.favorites)||[];updatedAt=d&&d.updatedAt||'';render()})
    .catch(function(e){fst.textContent='Could not load favorites ('+e.message+'). Pull to refresh or try again later.'})
    .then(function(){loading=false});
  }

  function esc(s){return String(s==null?'':s).replace(/[&<>"']/g,function(c){return{'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]})}
  function safeUrl(u){u=String(u||'');return /^https:\/\//i.test(u)?u:'#'}
  var CTF;try{CTF=new Intl.DateTimeFormat('en-US',{timeZone:'America/Chicago',month:'short',day:'numeric',hour:'numeric',minute:'2-digit'})}catch(_){CTF=null}
  function when(f){
    if(f.favoritedAtIso&&CTF){var d=new Date(f.favoritedAtIso);if(!isNaN(d))return '~'+CTF.format(d)+' CT'}
    return f.favoritedAt||'';
  }
  function ts(f){var t=f.favoritedAtIso?Date.parse(f.favoritedAtIso):NaN;return isNaN(t)?-Infinity:t}
  // Fixed favoriter message: identical for everyone (no username/card name), shown once per person.
  var FIXED_MSG="Greetings ! I know trying to search a user's profile for cards is not available on Vinted nor is it easy to create bundles and search for specific cards, if you ever have any specific card(s) you are looking for just send me a message and we will look for you if needed.  Heads up , save money on bundles!";
  function personMsg(){return FIXED_MSG}
  // 'Message on Vinted': the same chat screen the "X added your item to their favorites" notification opens.
  // Link comes from the feed (publish.py message_link); if missing/malformed, rebuilt from the member + item IDs.
  // Tapping only copies the message and opens the chat; the user pastes and sends it themselves.
  var WANT_RE=/^https:\/\/www\.vinted\.[a-z.]+\/inbox\/want_it\?receiver_id=\d+&item_id=\d+$/i;
  function idOf(re,s){var m=re.exec(String(s||''));return m?m[1]:''}
  function msgLink(f){
    var u=f.message_link||f.messageLink||'';if(WANT_RE.test(u))return u;
    var mid=/^\d+$/.test(f.member_id||'')?f.member_id:idOf(/\/member\/(?:general\/)?(\d+)/,f.profileLink||f.profile_link);
    var iid=/^\d+$/.test(f.item_id||'')?f.item_id:idOf(/\/items\/(\d+)/,f.itemLink||f.item_link);
    return mid&&iid?'https://www.vinted.com/inbox/want_it?receiver_id='+mid+'&item_id='+iid:'';
  }
  function mvBtn(f,mi,sub){
    var u=msgLink(f);if(!u)return '';
    return '<a class="mv" href="'+esc(u)+'" target="_blank" rel="noopener" data-m="'+mi+'" title="Copies the message, then opens the Vinted chat for this buyer and item">Message on Vinted'+(sub?'<small>'+esc(sub)+'</small>':'')+'</a>';
  }
  function groupBy(keyFn){
    var order=[],map={};
    data.forEach(function(f){var k=keyFn(f);if(!map[k]){map[k]=[];order.push(k)}map[k].push(f)});
    order.forEach(function(k){map[k].sort(function(a,b){return ts(b)-ts(a)})});
    order.sort(function(a,b){return ts(map[b][0])-ts(map[a][0])});
    return order.map(function(k){return map[k]});
  }
  var msgs=[];
  // @username = same as tapping the Vinted favorite notification: copies the message and opens the want_it chat
  // (fs[0] = this item's favorite, or in Group by person the person's most recent favorite). Small 'profile' link beside it.
  function row(name,link,time,msg,extra,favsForBtns){
    msgs.push(msg);var mi=msgs.length-1,fs=favsForBtns||[],multi=fs.length>1,ml=fs.length?msgLink(fs[0]):'';
    var un=ml?'<a class="un" href="'+esc(ml)+'" target="_blank" rel="noopener" data-m="'+mi+'" title="Copies the message, then opens the Vinted chat for this buyer'+(multi?' (most recent item)':' and item')+'">'+esc(name)+'</a>'
             :'<a href="'+esc(safeUrl(link))+'" target="_blank" rel="noopener">'+esc(name)+'</a>';
    var pf=ml&&safeUrl(link)!=='#'?'<a class="pf" href="'+esc(safeUrl(link))+'" target="_blank" rel="noopener" title="Open Vinted profile">profile</a>':'';
    return '<div class="fr"><div class="who">'+un+pf+'<span class="tm">'+esc(time)+'</span></div>'+(extra||'')+
      '<div class="msg"><div>'+esc(msg)+'</div><div class="acts"><button type="button" class="cp" data-m="'+mi+'">Copy</button>'+
      fs.map(function(f){return mvBtn(f,mi,multi?f.item:'')}).join('')+'</div></div></div>';
  }
  function render(){
    if(!data)return;
    var v=fq.value.toLowerCase().trim(),byP=fp.checked,h='',ng=0,nf=0;msgs=[];
    function hit(s){return !v||String(s||'').toLowerCase().indexOf(v)>=0}
    if(!byP){
      groupBy(function(f){return f.itemLink||f.item}).forEach(function(g){
        var it=g[0],itemHit=hit(it.item),rows=g.filter(function(f){return itemHit||hit(f.username)});
        if(!rows.length)return;ng++;nf+=rows.length;
        var users={};g.forEach(function(f){users[f.username]=1});var n=Object.keys(users).length;
        h+='<div class="fg"><div class="fh"><a href="'+esc(safeUrl(it.itemLink))+'" target="_blank" rel="noopener">'+esc(it.item)+'</a><span class="pr">'+esc(it.price)+'</span><span class="ct">\u2605 '+n+' favoriter'+(n===1?'':'s')+'</span></div>'+
          rows.map(function(f){return row(f.username,f.profileLink,when(f),f.message||FIXED_MSG,'',[f])}).join('')+'</div>';
      });
    }else{
      groupBy(function(f){return f.username}).forEach(function(g){
        var u=g[0].username,ok=hit(u)||g.some(function(f){return hit(f.item)});
        if(!ok)return;ng++;nf+=g.length;
        var items='<ul class="its">'+g.map(function(f){return '<li><a href="'+esc(safeUrl(f.itemLink))+'" target="_blank" rel="noopener">'+esc(f.item)+'</a> \u00b7 '+esc(f.price)+' \u00b7 <span class="tm">'+esc(when(f))+'</span></li>'}).join('')+'</ul>';
        h+='<div class="fg"><div class="fh"><span class="ct">'+g.length+' item'+(g.length===1?'':'s')+' favorited</span></div>'+
          row(u,g[0].profileLink,'latest '+when(g[0]),personMsg(u,g),items,g)+'</div>';
      });
    }
    var up='';if(updatedAt&&CTF){var d=new Date(updatedAt);if(!isNaN(d))up=' \u00b7 Feed updated ~'+CTF.format(d)+' CT'}
    fst.textContent=(byP?ng+' '+(ng===1?'person':'people'):ng+' item'+(ng===1?'':'s'))+' \u00b7 '+nf+' favorite'+(nf===1?'':'s')+(v?' (filtered)':'')+up;
    fl.innerHTML=h||'<div class="fst">'+(data.length?'No favorites match your search.':'No favorites yet.')+'</div>';
  }
  function fallbackCopy(t){
    var a=document.createElement('textarea');a.value=t;a.setAttribute('readonly','');a.style.cssText='position:fixed;top:0;left:0;opacity:0;font-size:16px';
    document.body.appendChild(a);a.focus();a.select();try{a.setSelectionRange(0,t.length)}catch(_){}
    var ok=false;try{ok=document.execCommand('copy')}catch(_){}document.body.removeChild(a);return ok;
  }
  function flash(b,ok){b.textContent=ok?'Copied!':'Copy failed';b.className='cp'+(ok?' ok':'');setTimeout(function(){b.textContent='Copy';b.className='cp'},1500)}
  var toastEl=null,toastT=0;
  function toast(t,bad){
    if(!toastEl){toastEl=document.createElement('div');toastEl.id='ftoast';toastEl.setAttribute('role','status');toastEl.setAttribute('aria-live','polite');document.body.appendChild(toastEl)}
    toastEl.textContent=t;toastEl.className='on'+(bad?' bad':'');clearTimeout(toastT);toastT=setTimeout(function(){toastEl.className=bad?'bad':''},3500);
  }
  // Message on Vinted: copy synchronously inside the tap (so it still works once the new tab/app takes focus),
  // then let the <a target=_blank> open the chat natively (no popup blocker; Vinted app via app links on phones).
  fl.addEventListener('click',function(e){
    var a=e.target.closest('.mv,.un');if(!a)return;
    var t=msgs[+a.getAttribute('data-m')]||'',ok=fallbackCopy(t);
    function done(ok){
      if(ok){toast('Message copied, paste it in the chat');a.classList.add('ok');setTimeout(function(){a.classList.remove('ok')},1500)}
      else toast('Could not copy automatically \u2014 tap Copy, then paste it in the chat',true);
    }
    if(!ok&&navigator.clipboard&&window.isSecureContext){navigator.clipboard.writeText(t).then(function(){done(true)},function(){done(false)})}
    else done(ok);
  });
  fl.addEventListener('click',function(e){
    var b=e.target.closest('.cp');if(!b)return;var t=msgs[+b.getAttribute('data-m')]||'';
    if(navigator.clipboard&&window.isSecureContext){navigator.clipboard.writeText(t).then(function(){flash(b,true)},function(){flash(b,fallbackCopy(t))})}
    else flash(b,fallbackCopy(t));
  });
  fq.addEventListener('input',render);fp.addEventListener('change',render);
  document.addEventListener('visibilitychange',function(){if(!document.hidden&&!fav.hidden)load()});
  show(/^#fav/i.test(location.hash)?'fav':'inv');
})();
